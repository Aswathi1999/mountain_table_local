// --- SEO per route, from the archived raw <head> of each page.
const dec = (s) =>
  (s ?? "")
    .replace(/&amp;/g, "&")
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .trim();
const routes = { "/": "home", "/about": "about", "/see-do": "see-do", "/rooms-booking": "rooms-booking" };
const seo = {};
for (const [route, page] of Object.entries(routes)) {
  const head = JSON.parse(readFileSync(`archive/content/${page}.json`, "utf8")).head;
  const meta = (key) => dec(head.metas.find((x) => x.includes(`"${key}"`))?.match(/content="([\s\S]*?)"/)?.[1]);
  seo[route] = {
    title: dec(head.title),
    description: meta("description"),
    ogTitle: meta("og:title"),
    ogDescription: meta("og:description"),
    ogUrl: meta("og:url"),
    twitterTitle: meta("twitter:title"),
    twitterDescription: meta("twitter:description"),
    jsonLd: head.jsonld.map((s) => JSON.parse(s)),
  };
}
writeFileSync(
  "src/data/seo.ts",
  `// Generated by scripts/build-data.mjs from the original pages' <head>. Absolute URLs use SITE_URL at render time.
export type PageSeo = {
  title: string;
  description: string;
  ogTitle: string;
  ogDescription: string;
  ogUrl: string;
  twitterTitle: string;
  twitterDescription: string;
  jsonLd: Record<string, unknown>[];
};

export const seo: Record<string, PageSeo> = ${JSON.stringify(seo, null, 2)};
`,
);
