// --- Page copy, keyed by role. Source of truth: archive/content/<page>.json (Wix rich-text props).
const decode = (s) =>
  s
    .replace(/&#39;/g, "'")
    .replace(/&ldquo;/g, "“")
    .replace(/&rdquo;/g, "”")
    .replace(/&amp;/g, "&")
    .replace(/&nbsp;/g, " ")
    .replace(/​/g, "");
const paras = (page, id) => {
  const h = JSON.parse(readFileSync(`archive/content/${page}.json`, "utf8")).texts[`comp-${id}`];
  if (!h) throw new Error(`missing ${page}/${id}`);
  return decode(
    h
      .replace(/<br\s*\/?>/g, "\n")
      .replace(/<\/(p|h[1-6]|blockquote)>/g, "\n")
      .replace(/<[^>]+>/g, ""),
  )
    .split("\n")
    .map((s) => s.trim())
    .filter(Boolean);
};
